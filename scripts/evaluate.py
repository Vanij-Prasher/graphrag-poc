"""Compares plain vector RAG with hybrid GraphRAG on the test questions.

Run from the repo root:
    python scripts/evaluate.py            # runs any question/system not yet in the results
    python scripts/evaluate.py --report   # rebuilds the report from saved results (no API calls)
    python scripts/evaluate.py --rerun    # discards saved results and runs everything again

Results are saved after every question, so free-tier quota limits only pause the run:
rerun the next day and it continues where it stopped.

Scoring (no LLM judge, so it is objective and free):
    Retrieval: did the system retrieve every expected hotel, and how many hotels did it retrieve?
    Answer:    which hotel names appear in the answer? Correct = all expected hotels named
               and no other hotel named.
"""
import json
import re
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from backend.rag import GraphRAG, QuotaExceeded  # noqa: E402

EVAL_DIR = ROOT / "data" / "eval"
TESTS = EVAL_DIR / "test_set.json"
RESULTS = EVAL_DIR / "results.json"
REPORT = EVAL_DIR / "report.md"
SYSTEMS = {"vector_rag": "Vector RAG", "graph_rag": "GraphRAG (hybrid)"}
PAUSE_SECONDS = 8  # stay under free-tier requests-per-minute limits


def norm(text):
    return re.sub(r"[^a-z0-9]", "", text.lower())


def names_in(text, all_names):
    t = norm(text or "")
    return [n for n in all_names if norm(n) in t]


def run(rag, tests, results):
    for t in tests:
        for system in SYSTEMS:
            key = f"{system}:{t['id']}"
            if key in results:
                continue
            print(f"{t['id']} {SYSTEMS[system]:<18} ...", end=" ", flush=True)
            try:
                if system == "vector_rag":
                    r = rag.vector_rag(t["question"], complete=True)
                else:
                    r = rag.ask(t["question"], complete=True)
            except QuotaExceeded as e:
                print(f"\n\nStopped: {e}\nProgress is saved. Run again after the daily reset to continue.")
                return False
            results[key] = {
                "answer": r.get("answer", ""),
                "route": r.get("route"),
                "cypher": r.get("cypher"),
                "fallback": r.get("fallback"),
                "retrieved": r.get("hotels", []),
                "seconds": r.get("seconds"),
            }
            RESULTS.write_text(json.dumps(results, indent=2, ensure_ascii=False))
            print(f"done ({r.get('seconds')}s)")
            time.sleep(PAUSE_SECONDS)
    return True


def report(tests, results, all_names):
    lines = [
        "# Evaluation: vector RAG vs hybrid GraphRAG",
        "",
        "Generated by `scripts/evaluate.py`. Expected answers are computed from the source data "
        "(`data/eval/test_set.json`).",
        "",
        "- **Retrieved all:** every expected hotel was in the retrieved context.",
        "- **Answer:** ✓ named all expected hotels and no others; ~ named some; ✗ named none.",
        "",
        "| Q | Expected | System | Route | Retrieved all? | # retrieved | Answer | Extra hotels named |",
        "|---|---|---|---|---|---|---|---|",
    ]
    totals = {s: {"correct": 0, "retrieved_all": 0, "retrieved": 0, "n": 0, "seconds": 0.0} for s in SYSTEMS}
    for t in tests:
        exp = set(t["expected"])
        for system, label in SYSTEMS.items():
            r = results.get(f"{system}:{t['id']}")
            if not r:
                lines.append(f"| {t['id']} | {', '.join(t['expected'])} | {label} | | not run | | | |")
                continue
            named = set(names_in(r["answer"], all_names))
            found, extra = named & exp, named - exp
            verdict = "✓" if found == exp and not extra else ("~" if found else "✗")
            got_all = exp <= set(r["retrieved"])
            tot = totals[system]
            tot["n"] += 1
            tot["correct"] += verdict == "✓"
            tot["retrieved_all"] += got_all
            tot["retrieved"] += len(r["retrieved"])
            tot["seconds"] += r["seconds"] or 0
            route = r["route"] or "vector only"
            if r.get("fallback"):
                route += " (fallback)"
            lines.append(
                f"| {t['id']} | {', '.join(t['expected'])} | {label} | {route} | "
                f"{'yes' if got_all else 'no'} | {len(r['retrieved'])} | {verdict} | {', '.join(sorted(extra)) or '-'} |"
            )
    lines += ["", "## Summary", "", "| System | Correct answers | Retrieved all expected | Avg hotels retrieved | Avg seconds |", "|---|---|---|---|---|"]
    for system, label in SYSTEMS.items():
        tot = totals[system]
        n = tot["n"] or 1
        lines.append(
            f"| {label} | {tot['correct']}/{tot['n']} | {tot['retrieved_all']}/{tot['n']} | "
            f"{tot['retrieved'] / n:.1f} | {tot['seconds'] / n:.1f} |"
        )
    REPORT.write_text("\n".join(lines) + "\n")
    print("\n" + "\n".join(lines[-4:]))
    print(f"\nFull report: {REPORT.relative_to(ROOT)}")


def main():
    tests = json.loads(TESTS.read_text())
    if "--rerun" in sys.argv and RESULTS.exists():
        RESULTS.unlink()
    results = json.loads(RESULTS.read_text()) if RESULTS.exists() else {}

    rag = GraphRAG()
    try:
        records, _, _ = rag.driver.execute_query("MATCH (h:Hotel) RETURN h.name AS name", database_=rag.db)
        all_names = [r["name"] for r in records]
        if "--report" not in sys.argv:
            done = sum(1 for t in tests for s in SYSTEMS if f"{s}:{t['id']}" in results)
            print(f"{done}/{len(tests) * len(SYSTEMS)} runs already saved\n")
            run(rag, tests, results)
    finally:
        rag.close()
    report(tests, results, all_names)


if __name__ == "__main__":
    main()
